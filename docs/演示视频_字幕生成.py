import time


def write_retry(path, text):
    """百度网盘同步/杀软可能短暂占用文件，写入失败时重试。"""
    for attempt in range(10):
        try:
            path.write_text(text, encoding="utf-8")
            return
        except PermissionError:
            if attempt == 9:
                raise
            time.sleep(1.5)


